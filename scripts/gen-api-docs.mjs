#!/usr/bin/env node
/**
 * Regenerate the resource tables in docs/API.md from the live OpenAPI document.
 *
 *   node scripts/gen-api-docs.mjs                 # fetches http://localhost:3001/api/v1/openapi.json
 *   node scripts/gen-api-docs.mjs --base https://app.example.com
 *   node scripts/gen-api-docs.mjs --from openapi.json   # from a saved snapshot
 *   node scripts/gen-api-docs.mjs --check          # exit 1 when docs/API.md is stale (CI)
 *
 * No dependencies. The OpenAPI document is the single source of truth (it is
 * built by `buildOpenApiDocument()` from `src/lib/public-api/registry.ts`);
 * this script only rewrites the block between the markers
 * `<!-- gen:resources -->` and `<!-- /gen:resources -->`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const args = process.argv.slice(2);
const opt = (name, fallback) => {
  const i = args.indexOf(name);
  return i === -1 ? fallback : args[i + 1];
};
const base = (opt("--base", process.env.API_DOCS_BASE ?? "http://localhost:3001")).replace(/\/$/, "");
const from = opt("--from", null);
const check = args.includes("--check");
const docPath = resolve(process.cwd(), "docs/API.md");

async function loadSpec() {
  if (from) return JSON.parse(readFileSync(resolve(process.cwd(), from), "utf8"));
  const res = await fetch(`${base}/api/v1/openapi.json`, { signal: AbortSignal.timeout(15_000) });
  if (!res.ok) throw new Error(`GET ${base}/api/v1/openapi.json → ${res.status}`);
  return res.json();
}

function render(spec) {
  const byTag = new Map();
  for (const [path, methods] of Object.entries(spec.paths)) {
    for (const [method, op] of Object.entries(methods)) {
      const tag = op.tags?.[0] ?? "Other";
      if (!byTag.has(tag)) byTag.set(tag, []);
      byTag.get(tag).push({ method: method.toUpperCase(), path, op });
    }
  }
  const tagOrder = (spec.tags ?? []).map((t) => t.name);
  const tags = [...byTag.keys()].sort((a, b) => (tagOrder.indexOf(a) === -1 ? 999 : tagOrder.indexOf(a)) - (tagOrder.indexOf(b) === -1 ? 999 : tagOrder.indexOf(b)));
  const lines = [];
  const total = [...byTag.values()].reduce((n, v) => n + v.length, 0);
  lines.push(`_${Object.keys(spec.paths).length} paths · ${total} operations · generated by \`scripts/gen-api-docs.mjs\` from \`GET /api/v1/openapi.json\`._`, "");
  for (const tag of tags) {
    const desc = (spec.tags ?? []).find((t) => t.name === tag)?.description;
    lines.push(`### ${tag}`, "");
    if (desc) lines.push(desc, "");
    lines.push("| Operation | Route | Scope | Tools |", "| --- | --- | --- | --- |");
    for (const { method, path, op } of byTag.get(tag).sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method))) {
      const scope = op["x-scope"] ? `\`${op["x-scope"]}\`` : "public";
      const tools = (op["x-kernelhub-tools"] ?? []).map((t) => `\`${t}\``).join(", ") || "—";
      const summary = String(op.summary ?? op.operationId).replace(/\|/g, "\\|");
      lines.push(`| ${summary} | \`${method} ${path}\` | ${scope} | ${tools} |`);
    }
    lines.push("");
  }
  return lines.join("\n").trimEnd();
}

const START = "<!-- gen:resources -->";
const END = "<!-- /gen:resources -->";

const spec = await loadSpec();
const doc = readFileSync(docPath, "utf8");
const s = doc.indexOf(START);
const e = doc.indexOf(END);
if (s === -1 || e === -1 || e < s) {
  console.error(`docs/API.md must contain ${START} … ${END}`);
  process.exit(2);
}
const next = `${doc.slice(0, s + START.length)}\n${render(spec)}\n${doc.slice(e)}`;
if (next === doc) {
  console.log("docs/API.md is up to date");
} else if (check) {
  console.error("docs/API.md is stale — run `node scripts/gen-api-docs.mjs`");
  process.exit(1);
} else {
  writeFileSync(docPath, next);
  console.log(`docs/API.md updated (${Object.keys(spec.paths).length} paths)`);
}
